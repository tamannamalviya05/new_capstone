with source_data as (
   SELECT
   DELIVERY_ID,
   DELIVERY_TIMESTAMP,
   INNINGS_NO,
   OVER_NO,   
   BALL_IN_OVER,
   RUNS_OFF_BAT,
   EXTRA_TYPE,
   EXTRA_RUNS,
   TOTAL_RUNS,
   IS_WICKET,
   DISMISSAL_TYPE,
   BALL_SPEED_KMPH,
   NON_STRICKER_ID,
   SHOT_TYPE,
   SHOT_REGION,
   MATCH_ID,
   MATCH_DATE,
   MATCH_FORMAT,
   TOURNAMENT_NAME,
   SEASON,
   MATCH_STAGE,
   TOSS_DECISION,
   VENUE_ID,
   VENUE_NAME,
   VENUE_CITY,
   VENUE_COUNTRY,
   BATTING_TEAM_ID,
   BATTING_TEAM_NAME,
   BOWLING_TEAM_ID,
   BOWLING_TEAM_NAME,
   BATSMAN_ID,
   BATSMAN_NAME,
   BATSMAN_DOB,
   BATSMAN_NATIONALITY,
   BATTING_HAND,
   BATSMAN_ROLE,
   BATSMAN_EMAIL,
   BATSMAN_PHONE,
   BATSMAN_ICC_RATING, 
   BOWLER_ID,
   BOWLER_NAME,
   BOWLER_NATIONALITY,
   BOWLING_STYLE,
   BOWLER_ICC_RATING,
   CONTRACT_ID,
   CONTRACT_GRADE,
   ANNUAL_RETAINER_USD,
   CONTRACT_STATUS,
   DRS_REVIEW_ID,
   DRS_REVIEWED_BY,
   DRS_ORIGINAL_DECISION,
   DRS_OUTCOME,
   _SOURCE_FILE,
   _LOADED_AT
   FROM {{ source ('raw', 'raw_cricket_data') }}
)

SELECT 
   TRIM(DELIVERY_ID) AS DELIVERY_ID,
   COALESCE(
    TRY_TO_DATE(TRIM(DELIVERY_TIMESTAMP), 'DD-MM-YYYY'),
    TRY_TO_DATE(TRIM(DELIVERY_TIMESTAMP), 'MM-DD-YYYY'),
    TRY_TO_DATE(TRIM(DELIVERY_TIMESTAMP), 'MM/DD/YYYY'),
    TRY_TO_TIMESTAMP_NTZ(TRIM(DELIVERY_TIMESTAMP))::DATE) AS DELIVERY_TIMESTAMP,
   TRY_CAST(TRIM(INNINGS_NO) AS INTEGER) AS INNINGS_NO,
   TRY_CAST(TRIM(OVER_NO) AS INTEGER) AS OVER_NO,
   TRY_CAST(TRIM(BALL_IN_OVER) AS INTEGER) AS BALL_IN_OVER,
   TRY_CAST(TRIM(RUNS_OFF_BAT) AS INTEGER) AS RUNS_OFF_BAT,
   TRIM(CASE WHEN EXTRA_TYPE IN ('NO BALL', 'No Ball', 'no-ball','nb', 'Noball')
        THEN 'No Ball'
        WHEN UPPER(EXTRA_TYPE) IN ('WIDE', 'Wd', 'wide', 'Wide', 'wd')
        THEN 'Wide'
        WHEN UPPER(EXTRA_TYPE) IN ('Bye', 'BYE')
        THEN 'Bye'
        WHEN UPPER(EXTRA_TYPE) IN ('LEG BYE', 'Leg Bye', 'Ledbye', 'lb')
        THEN 'Leg Bye'
        WHEN UPPER(EXTRA_TYPE) IN ('BYES', 'byes', 'b')
        THEN 'Byes'
    END) AS EXTRA_TYPE,
    TRY_CAST(EXTRA_RUNS AS INTEGER) AS EXTRA_RUNS,
    TRY_CAST(TOTAL_RUNS AS INTEGER) AS TOTAL_RUNS,
    CASE WHEN UPPER(TRIM(IS_WICKET)) IN ('TRUE', 'Y', 'YES', '1', 'OUT')
         THEN TRUE
         WHEN UPPER(TRIM(IS_WICKET)) IN ('FALSE', 'F', 'NO', '0', 'N')
         THEN FALSE 
    END AS IS_WICKET,
    TRIM(DISMISSAL_TYPE) AS DISMISSAL_TYPE,
    TRY_TO_DECIMAL(TRIM(BALL_SPEED_KMPH), 18,2) AS BALL_SPEED_KMPH,
    TRIM(NON_STRICKER_ID) AS NON_STRICKER_ID,
    TRIM(SHOT_TYPE) AS SHOT_TYPE,
    TRIM(SHOT_REGION) AS SHOT_REGION,
    TRIM(MATCH_ID) AS MATCH_ID,
    COALESCE(
     TRY_TO_DATE(TRIM(MATCH_DATE), 'DD-MM-YYYY'),
     TRY_TO_DATE(TRIM(MATCH_DATE), 'MM-DD-YYYY'),
     TRY_TO_DATE(TRIM(MATCH_DATE), 'MM/DD/YYYY'),
     TRY_TO_TIMESTAMP_NTZ(TRIM(MATCH_DATE))::DATE) AS MATCH_DATE,
    TRIM(MATCH_FORMAT) AS MATCH_FORMAT,
    TRIM(UPPER(TOURNAMENT_NAME)) AS TOURNAMENT_NAME,
    TRY_CAST(TRIM(SEASON) AS INTEGER) AS SEASON,
    TRIM(MATCH_STAGE) AS MATCH_STAGE,
    TRIM(TOSS_DECISION) AS TOSS_DECISION,
    TRIM(VENUE_ID) AS VENUE_ID,
    TRIM(UPPER(VENUE_NAME)) AS VENUE_NAME,
    TRIM(UPPER(VENUE_CITY)) AS VENUE_CITY,
    TRIM(UPPER(VENUE_COUNTRY)) AS VENUE_COUNTRY,
    TRIM(BATTING_TEAM_ID) AS BATTING_TEAM_ID,
    TRIM(BATTING_TEAM_NAME) AS BATTING_TEAM_NAME,
    TRIM(BOWLING_TEAM_ID) AS BOWLING_TEAM_ID,
    TRIM(BOWLING_TEAM_NAME) AS BOWLING_TEAM_NAME,
    TRIM(BATSMAN_ID) AS BATSMAN_ID,
    TRIM(BATSMAN_NAME) AS BATSMAN_NAME,
    COALESCE(
     TRY_TO_DATE(TRIM(BATSMAN_DOB), 'DD-MM-YYYY'),
     TRY_TO_DATE(TRIM(BATSMAN_DOB), 'MM-DD-YYYY'),
     TRY_TO_DATE(TRIM(BATSMAN_DOB), 'MM/DD/YYYY'),
     TRY_TO_TIMESTAMP_NTZ(TRIM(BATSMAN_DOB))::DATE) AS BATSMAN_DOB,
    TRIM(UPPER(BATSMAN_NATIONALITY)) AS BATSMAN_NATIONALITY,
    TRIM(BATTING_HAND) AS BATTING_HAND,
    TRIM(BATSMAN_ROLE) AS BATSMAN_ROLE,
    LOWER(TRIM(BATSMAN_EMAIL)) AS BATSMAN_EMAIL,
    TRY_CAST(BATSMAN_PHONE AS INTEGER) AS BATSMAN_PHONE,
    TRY_CAST(BATSMAN_ICC_RATING AS INTEGER) AS BATSMAN_ICC_RATING,
TRIM(BOWLER_ID) AS BOWLER_ID,
    TRIM(BOWLER_NAME) AS BOWLER_NAME,
    TRIM(UPPER(BOWLER_NATIONALITY)) AS BOWLER_NATIONALITY,
    TRIM(BOWLING_STYLE) AS BOWLING_STYLE,
    TRY_CAST(BOWLER_ICC_RATING AS INTEGER) AS BOWLER_ICC_RATING,   
    TRIM(CONTRACT_ID) AS CONTRACT_ID,
    TRIM(CONTRACT_GRADE) AS CONTRACT_GRADE,
    TRY_TO_DECIMAL(TRIM(ANNUAL_RETAINER_USD), 18, 2) AS ANNUAL_RETAINER_USD,
    TRIM(CONTRACT_STATUS) AS CONTRACT_STATUS,
    TRIM(DRS_REVIEW_ID) AS DRS_REVIEW_ID,
    TRIM(DRS_REVIEWED_BY) AS DRS_REVIEWED_BY,
    TRIM(DRS_ORIGINAL_DECISION) AS DRS_ORIGINAL_DECISION,
    TRIM(DRS_OUTCOME) AS DRS_OUTCOME,
    _SOURCE_FILE,
    _LOADED_AT
FROM source_data

QUALIFY ROW_NUMBER() OVER (PARTITION BY DELIVERY_ID ORDER BY _LOADED_AT DESC ) = 1

